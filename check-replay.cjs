const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const storage=new Map();
const localStorage={getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value)};
const context=vm.createContext({localStorage});
vm.runInContext(fs.readFileSync('dist/replay.js','utf8'),context);
const replay=context.ExamReplay;
function exam(id='one'){return {attempt:id,ids:['c2','p3'],deadline:10_000,finished:false,replay:replay.create()};}
const attempt=exam();
replay.checkpoint(attempt,'c2',true,1_000);
replay.checkpoint(attempt,'p3',true,3_500);
assert.equal(attempt.replay.times.c2,2_500);
replay.checkpoint(attempt,'p3',false,5_000);
assert.equal(attempt.replay.times.p3,1_500);
replay.checkpoint(attempt,'p3',true,8_000);
replay.checkpoint(attempt,'p3',false,13_000);
assert.equal(attempt.replay.times.p3,3_500);
assert.equal(attempt.replay.focus,null);
const first={action:'start',questionId:'c2',runId:'run1',kind:'sql',text:'SELECT SUM(i.Total) FROM Invoice i JOIN InvoiceLine l ON l.InvoiceId=i.InvoiceId;',mode:'rows'};
replay.record(attempt,first,2_000);
replay.record(attempt,first,2_001);
assert.equal(attempt.replay.events.length,1);
replay.record(attempt,{action:'finish',questionId:'c2',runId:'run1',status:'incorrect',summary:'20,848.62'},3_000);
replay.record(attempt,{...first,runId:'run2',text:'SELECT SUM(Total) FROM Invoice;'},4_000);
replay.record(attempt,{action:'finish',questionId:'c2',runId:'run2',status:'correct',summary:'2,328.60'},5_000);
replay.draft(attempt,'c2',{kind:'sql',text:'SELECT 1;',mode:'rows'});
assert.equal(attempt.replay.events[0].status,'incorrect');
assert.equal(attempt.replay.events[1].text,'SELECT SUM(Total) FROM Invoice;');
assert.equal(attempt.replay.events[1].status,'correct');
assert.equal(attempt.replay.drafts.c2.text,'SELECT 1;');
replay.record(attempt,{...first,runId:'run3'},6_000);
replay.interrupt(attempt,6_500);
assert.equal(attempt.replay.events[2].status,'interrupted');
replay.record(attempt,{...first,questionId:'unknown',runId:'bad'},7_000);
assert.equal(attempt.replay.events.length,3);
attempt.finished=true;
assert(replay.complete(attempt,14_000));
assert(replay.complete(attempt,14_000));
assert.equal(replay.history().length,1);
for(let i=0;i<6;i++)assert(replay.complete(exam('exam-'+i),15_000+i));
assert.equal(replay.history().length,5);
assert.equal(replay.history()[0].attempt,'exam-5');
assert(!replay.history().some(item=>item.attempt==='one'));
assert(replay.complete({attempt:'legacy',ids:['c2']},20_000));
assert.equal(replay.history().length,5);
storage.set('accountingLab.replays.v1','broken JSON');
assert.equal(replay.history().length,0);
storage.set('accountingLab.replays.v1',JSON.stringify([{ids:['c2'],replay:{version:1}}]));
assert.equal(replay.history().length,0);
console.log('Replay checks passed for viewed time, pauses, deadline expiry, run snapshots, duplicate messages, interruptions, legacy sessions and five saved replays.');
